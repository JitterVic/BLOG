def collect_attributes(html: str) -> list[tuple[str, str, str | None]]:
    """列出渲染结果中真实存在的属性（标签名, 属性名, 属性值）。

    去掉 attr_list 后这些 payload 会退化成转义后的可见文本，断言必须看属性位置
    而不是子串，否则文本里的 "onclick" 会造成假失败。
    """
    from html.parser import HTMLParser

    found: list[tuple[str, str, str | None]] = []

    class Collector(HTMLParser):
        def handle_starttag(self, tag, attrs):
            for name, value in attrs:
                found.append((tag, name.lower(), value))

        handle_startendtag = handle_starttag

    parser = Collector()
    parser.feed(html)
    parser.close()
    return found


@pytest.mark.parametrize(
    "source",
    [
        '# 标题 {: onclick="alert(1)" }',
        '段落 {: onmouseover="alert(1)" }',
        '## 小节 {: style="x:expression(alert(1))" }',
        '### 头 {: id="x" class="y" }',
    ],
)
def test_markdown_pipeline_never_emits_event_or_style_attributes(source):
    render_markdown = importlib.import_module("blog.markdown_tools").render_markdown
    html = render_markdown(source)
    attributes = collect_attributes(html)
    offending = [
        item for item in attributes
        if item[1].startswith("on") or item[1] in {"style", "id"}
    ]
    assert not offending, f"渲染结果带出危险属性：{offending}"


