def test_viewed_posts_cookie_stays_under_browser_limit(app_bundle, client):
    """80 篇长中文 slug 后 cookie 仍需远小于浏览器 4093 字节上限。"""
    _application, store = app_bundle
    cjk = "深入理解应用工厂蓝图注册机制读写权衡编辑部风格首页布局渲染管线白名单设计复盘"
    slugs = []
    for index in range(85):
        title = "".join(cjk[(index + offset) % len(cjk)] for offset in range(55)) + str(index)
        post_id = store.save_post(
            {"title": title, "markdown_content": "正文内容 " * 30}, action="published"
        )
        slugs.append(store.get_post_by_id(post_id)["slug"])

    largest = 0
    with warnings.catch_warnings(record=True) as caught:
        warnings.simplefilter("always")
        for slug in slugs:
            response = client.get(f"/api/posts/{slug}")
            assert response.status_code == 200
            for cookie in response.headers.getlist("Set-Cookie"):
                largest = max(largest, len(cookie))
        oversize = [w for w in caught if "too large" in str(w.message)]

    assert not oversize, "werkzeug 报告 session cookie 过大"
    assert largest <= 4093, f"Set-Cookie 达到 {largest} 字节"

    with client.session_transaction() as session:
        assert len(session["viewed_posts"]) <= 80


