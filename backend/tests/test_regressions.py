def test_login_throttle_state_is_shared_across_app_instances(tmp_path, monkeypatch):
    """模拟两个 gunicorn worker：各自建 app，共用一个数据库。"""
    monkeypatch.setenv("BLOG_DEBUG", "true")
    monkeypatch.setenv("BLOG_SECRET_KEY", "test-secret-key")
    monkeypatch.setenv("BLOG_ADMIN_PASSWORD", "test-password")
    monkeypatch.setenv("BLOG_ADMIN_PREFIX", "/admin")
    monkeypatch.setenv("BLOG_DATABASE_PATH", str(tmp_path / "shared.db"))
    monkeypatch.setenv("BLOG_LOGIN_MAX_ATTEMPTS", "4")
    monkeypatch.setenv("BLOG_LOGIN_RATE_WINDOW_SECONDS", "300")
    monkeypatch.setenv("BLOG_TRUSTED_PROXY_COUNT", "0")

    app_module = importlib.import_module("blog.app")
    worker_one = app_module.create_app()
    worker_two = app_module.create_app()

    def bad_login(application):
        test_client = application.test_client()
        test_client.get("/admin/login")
        with test_client.session_transaction() as session:
            token = session["_admin_csrf_token"]
        return test_client.post(
            "/admin/login", data={"password": "wrong", "csrf_token": token}
        )

    # 两次打 worker one，两次打 worker two —— 合计 4 次即应触发限流。
    assert bad_login(worker_one).status_code == 200
    assert bad_login(worker_one).status_code == 200
    assert bad_login(worker_two).status_code == 200
    assert bad_login(worker_two).status_code == 200

    # 第五次无论落到哪个 worker 都必须 429。
    assert bad_login(worker_one).status_code == 429
    assert bad_login(worker_two).status_code == 429

    # 新建实例（等价于 worker 回收 / 进程重启）不得重置计数。
    recycled = app_module.create_app()
    assert bad_login(recycled).status_code == 429


def test_login_throttle_survives_store_failure(tmp_path, monkeypatch):
    """SQLite 不可用时退回内存计数，登录路径不应整体报错。"""
    from blog.login_throttle import LoginFailureStore

    class BrokenDatabase:
        def connect(self):
            import sqlite3

            raise sqlite3.OperationalError("disk offline")

    store = LoginFailureStore(BrokenDatabase(), window_seconds=300, max_keys=16)
    # 用当前时钟：__len__ 按“当前窗口内”统计，固定的假时间戳会直接过期。
    now = time.time()
    store.record_failure("1.2.3.4", now=now)
    store.record_failure("1.2.3.4", now=now + 1)
    assert len(store.attempts("1.2.3.4", now=now + 2)) == 2
    assert len(store) == 1
    store.clear()
    assert len(store) == 0

    # 过期的时间戳不应再计入。
    store.record_failure("5.6.7.8", now=now - 10_000)
    assert store.attempts("5.6.7.8") == []
